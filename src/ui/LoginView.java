    private void btnConnecterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConnecterActionPerformed
        // TODO add your handling code here:
        try{
            String email = txtAdresseEmail.getText();
            String motDePasse = txtMotDePasse.getText();

            if (email.isEmpty() || motDePasse.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this,
                "Veuillez remplir tous les champs.",
                "Erreur",
                javax.swing.JOptionPane.WARNING_MESSAGE);
                return;
            }

            Utilisateur u = listing.connecter(email, motDePasse);

            if (u != null) {
                javax.swing.JOptionPane.showMessageDialog(this,
                "Bienvenue " + u.getPrenom() + " " + u.getNom(),
                "Connexion réussie",
                javax.swing.JOptionPane.INFORMATION_MESSAGE);
            } else {
                javax.swing.JOptionPane.showMessageDialog(this,
                "Email ou mot de passe incorrect.",
                "Erreur",
                javax.swing.JOptionPane.ERROR_MESSAGE);
                txtMotDePasse.setText("");
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this,
            "Une erreur inattendue s'est produite : " + e.getMessage(),
            "Erreur",
            javax.swing.JOptionPane.ERROR_MESSAGE);
        }    
    }//GEN-LAST:event_btnConnecterActionPerformed

